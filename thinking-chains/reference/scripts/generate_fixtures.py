def _sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _test_key_seed(label: str) -> bytes:
    """Deterministic TEST-ONLY Ed25519 seed for reproducible fixtures."""
    return hashlib.sha256(f"zoo.thinking-chains.fixture.test-key.v1:{label}".encode("utf-8")).digest()


def _discover_real_repo_files() -> list[dict[str, Any]]:
    """Collect real .tex and .md files from zoo-apps/papers for grounded input commitments."""
    candidates: list[Path] = []
    tc_dir = REPO_ROOT / "thinking-chains"
    for p in sorted(tc_dir.rglob("*.tex")):
        candidates.append(p)
    for subdir in sorted(REPO_ROOT.iterdir()):
        if not subdir.is_dir() or subdir.name in {"thinking-chains", ".git", "site", "pdfs", "shared"}:
            continue
        for p in sorted(subdir.glob("*.tex")):
            candidates.append(p)
    if len(candidates) < 25:
        raise RuntimeError(f"Expected >= 25 real .tex files in {REPO_ROOT}, found {len(candidates)}")

    files_info: list[dict[str, Any]] = []
    for p in candidates:
        raw = p.read_bytes()
        rel = p.relative_to(REPO_ROOT).as_posix()
        files_info.append(
            {
                "uri": f"repo://{rel}",
                "media_type": "text/x-tex",
                "byte_length": len(raw),
                "sha256": _sha256_hex(raw),
            }
        )
    return files_info


