def _sign_receipt(
    receipt: dict[str, Any],
    verifier_ids: list[tuple[str, str]],
    verifier_seeds: dict[str, bytes],
    attested_at_unix: int,
) -> dict[str, Any]:
    receipt["provenance"] = compute_provenance(receipt)
    rhash = canonical_receipt_hash(receipt)
    attestations = []
    for offset, (vid, role) in enumerate(verifier_ids):
        seed = verifier_seeds[vid]
        pub_hex = ed25519_public_key_from_seed(seed).hex()
        ts = attested_at_unix + offset + 1
        msg = attestation_message(rhash, vid, role, "VALID", ts)
        sig_hex = ed25519_sign(seed, msg).hex()
        attestations.append(
            {
                "verifier_id": vid,
                "verifier_role": role,
                "algorithm": "ed25519",
                "public_key_hex": pub_hex,
                "verdict": "VALID",
                "attested_receipt_hash": rhash,
                "attested_at_unix": ts,
                "signature_hex": sig_hex,
            }
        )
    receipt["attestations"] = attestations
    return receipt


